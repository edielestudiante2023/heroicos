    <h6 class="fw-bold text-center mb-2" style="font-size: 0.9rem;">AUTORIZACION PARA EL TRATAMIENTO DE DATOS PERSONALES</h6>
    <p class="text-center small text-muted mb-3">Academia de Futbol Heroicos — NIT: [NIT de la academia]</p>

    <p><strong>PRIMERO — Responsable del tratamiento:</strong>
    La ACADEMIA DE FUTBOL HEROICOS (en adelante "la Academia"), con domicilio en la ciudad de [Ciudad], es la responsable del tratamiento de los datos personales que usted suministra a traves de este formulario.</p>

    <p><strong>SEGUNDO — Marco normativo:</strong>
    El presente tratamiento se rige por la <strong>Ley 1581 de 2012</strong> (Regimen General de Proteccion de Datos Personales), el <strong>Decreto 1377 de 2013</strong> (reglamentario), la <strong>Ley 1098 de 2006</strong> (Codigo de la Infancia y la Adolescencia) y demas normas concordantes. En virtud del <strong>articulo 7 de la Ley 1581</strong>, los datos personales de niños, niñas y adolescentes son de <strong>naturaleza sensible</strong> y su tratamiento requiere autorizacion expresa del representante legal.</p>

    <p><strong>TERCERO — Finalidades del tratamiento:</strong></p>
    <ol type="a" class="mb-2">
        <li>Gestionar la inscripcion, matricula y participacion del(los) menor(es) en las actividades deportivas de la Academia.</li>
        <li>Mantener un registro actualizado de datos personales, medicos y deportivos del estudiante para la adecuada prestacion del servicio.</li>
        <li>Comunicar informacion relevante sobre horarios, eventos, torneos y actividades academicas/deportivas.</li>
        <li>Gestionar cobros, pagos y estados de cuenta relacionados con la prestacion del servicio.</li>
        <li>Atender emergencias medicas durante las actividades deportivas, utilizando la informacion de salud suministrada (EPS, grupo sanguineo, alergias, condiciones medicas, medicamentos, contacto de emergencia).</li>
        <li>Registrar asistencia y evaluar el progreso deportivo del estudiante.</li>
        <li>Cumplir obligaciones legales, regulatorias y contractuales.</li>
    </ol>

    <p><strong>CUARTO — Datos recolectados:</strong></p>
    <ul class="mb-2">
        <li><strong>Del acudiente/representante legal:</strong> nombres, apellidos, tipo y numero de documento de identidad, telefono, direccion, correo electronico.</li>
        <li><strong>Del menor:</strong> nombres, apellidos, tipo y numero de documento de identidad, fecha de nacimiento, sexo, fotografia, tallas de uniforme, posicion deportiva, pie dominante, EPS, grupo sanguineo/RH, alergias, condiciones medicas, medicamentos, contacto de emergencia.</li>
    </ul>

    <p><strong>QUINTO — Tratamiento de datos sensibles y de menores:</strong>
    De conformidad con los <strong>articulos 6 y 7 de la Ley 1581 de 2012</strong> y el <strong>articulo 12 del Decreto 1377 de 2013</strong>, los datos personales de menores de edad tienen naturaleza sensible. El tratamiento de estos datos responde al <strong>interes superior del menor</strong> y se realiza respetando sus derechos fundamentales. La Academia garantiza que el manejo de estos datos cumple con los requisitos de la <strong>Ley 1098 de 2006</strong>.</p>

    <p><strong>SEXTO — Uso de imagen y fotografia:</strong>
    La fotografia del menor sera utilizada exclusivamente para su identificacion dentro de los sistemas internos de la Academia. <strong>No sera publicada en redes sociales, paginas web ni medios externos</strong> sin autorizacion separada y expresa.</p>

    <p><strong>SEPTIMO — Derechos del titular:</strong>
    Como titular de los datos o representante legal del menor, usted tiene derecho a:</p>
    <ol type="a" class="mb-2">
        <li>Conocer, actualizar y rectificar sus datos personales y los del menor.</li>
        <li>Solicitar prueba de la autorizacion otorgada.</li>
        <li>Ser informado sobre el uso que se ha dado a los datos.</li>
        <li>Presentar quejas ante la Superintendencia de Industria y Comercio (SIC).</li>
        <li>Revocar la autorizacion y/o solicitar la supresion de los datos, siempre que no exista un deber legal o contractual que lo impida.</li>
        <li>Acceder gratuitamente a los datos personales tratados.</li>
    </ol>

    <p><strong>OCTAVO — Vigencia y almacenamiento:</strong>
    Los datos seran tratados mientras exista la relacion contractual con la Academia y hasta por <strong>cinco (5) años</strong> posteriores a la terminacion del vinculo, o el tiempo necesario para el cumplimiento de obligaciones legales.</p>

    <p><strong>NOVENO — Canales de atencion:</strong>
    Para ejercer sus derechos como titular puede comunicarse a: <strong>[email de la academia]</strong> o dirigirse a las instalaciones de la Academia.</p>

    <p class="mb-0"><strong>DECIMO — Seguridad:</strong>
    La Academia implementa medidas tecnicas, humanas y administrativas para proteger los datos personales contra acceso no autorizado, perdida, alteracion o uso indebido, conforme al <strong>articulo 4 literal g) de la Ley 1581 de 2012</strong>.</p>
